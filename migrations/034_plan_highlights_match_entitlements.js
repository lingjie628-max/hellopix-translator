/**
 * 让套餐卡片的宣传渠道与后台实际授权对齐。
 *
 * ## 起因
 *
 * 核对套餐权益时发现：官网三个套餐宣传的渠道，**没有一个**与
 * `package_engine_versions` 里新买家实际拿到的那套快照（catalog_version = 2）对得上。
 *
 *   套餐    highlights 原宣传              实际授权
 *   基础版  百度翻译、小牛翻译              DeepSeek、GPT、通义千问（3）
 *   高级版  谷歌翻译、+基础版各通道         基础版 3 条 + 豆包、GLM、MiniMax、Mistral（7）
 *   专业版  DeepL、亚马逊 AWS、+高级版      高级版 7 条 + Claude、谷歌、Grok、Kimi（11）
 *
 * 三处具体的错：
 *
 * 1. **「百度翻译」在 engines 表里根本不存在** —— 按 id / name 搜"百度"零条命中，
 *    却是基础版的第一条卖点。
 * 2. **小牛翻译、DeepL、亚马逊 AWS 已经停用**（`retired_at` 非空），却仍写在宣传里；
 *    其中 DeepL 与 AWS 是**最贵的专业版**的核心卖点。
 * 3. **高级版宣传「谷歌翻译」，而谷歌只授给了专业版** —— 客户为谷歌买高级版，
 *    一翻译必然撞上「当前套餐未包含此通道」。这条与当时那次
 *    "4 个商户一翻译就报错"同源：卖点与权益对不上，而报错文案商户看不懂。
 *
 * ## 改宣传，不改权益
 *
 * 已确认这几个渠道**不再上架**（百度从未有过，其余四条已退役），所以把宣传改成
 * 实际授权的渠道，而不是把权益补上这几个名字 —— 让权益去迁就一句过时的广告词
 * 是本末倒置，还会把已下架的上游重新暴露给客户。
 *
 * ## 为什么写进迁移而不是手动改库
 *
 * `packages.highlights` 是后台可编辑的数据。手动改完，开发库与生产库就会分叉，
 * 而且没人说得清"当时改成了什么"。写进迁移则可复现、可回滚、可审计 ——
 * 与 031 改 engines 数据是同一套做法。
 *
 * ## 文案怎么写的
 *
 * 保留原有的「+上一版各翻译通道」递进写法 —— 权益确实是包含关系（3 ⊂ 7 ⊂ 11），
 * 只写每档**新增**的渠道，免得专业版一行堆 11 个名字。
 * 每档新增的渠道是从快照里算出来的**差集**，不是手抄的。
 *
 * 「独立应用版 / 手机版」与渠道无关，本次不动。
 *
 * ## 防护
 *
 * 每一条 UPDATE 都**钉住那个已知的错误词**（百度翻译 / 谷歌翻译 / DeepL），
 * 只在文案确实还是那份错的、没被人改过时才覆盖 —— 沿用 031 修正 deepseek
 * 模型名时的做法：只改已经被证实错误的确切值，不无条件刷写生产配置。
 */

exports.up = pgm => {
  // ---------------------------------------------------------------------
  // 基础版：实际授权 DeepSeek / GPT / 通义千问 三条
  // 原宣传的「百度翻译」并不存在、「小牛翻译」已停用。
  // ---------------------------------------------------------------------
  pgm.sql(`
    UPDATE packages
    SET highlights = '["150万字符","DeepSeek、GPT、通义千问","独立应用版","手机版"]'::jsonb,
        updated_at = NOW()
    WHERE id = 1
      AND highlights::text LIKE '%百度翻译%';
  `)

  // ---------------------------------------------------------------------
  // 高级版：在基础版三条之上新增 豆包 / GLM / MiniMax / Mistral，共 7 条。
  // 原宣传的「谷歌翻译」不在这一档的授权里，是"卖点与权益错位"的那一处。
  // ---------------------------------------------------------------------
  pgm.sql(`
    UPDATE packages
    SET highlights = '["150万字符","豆包、GLM、MiniMax、Mistral","+基础版各翻译通道","独立应用版","手机版"]'::jsonb,
        updated_at = NOW()
    WHERE id = 2
      AND highlights::text LIKE '%谷歌翻译%';
  `)

  // ---------------------------------------------------------------------
  // 专业版：在高级版七条之上新增 Claude / 谷歌翻译 / Grok / Kimi，共 11 条。
  // 原宣传的 DeepL 与亚马逊 AWS 都已停用。
  // ---------------------------------------------------------------------
  pgm.sql(`
    UPDATE packages
    SET highlights = '["150万字符","Claude、谷歌翻译、Grok、Kimi","+高级版各翻译通道","独立应用版","手机版"]'::jsonb,
        updated_at = NOW()
    WHERE id = 3
      AND highlights::text LIKE '%DeepL%';
  `)
}

