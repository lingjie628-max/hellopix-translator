const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const LOG = '/tmp/ctx.log'
const w = s => fs.appendFileSync(LOG, s + '\n')
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, webPreferences: { sandbox: true, contextIsolation: true, preload: require('node:path').join(__dirname, 'ctx-preload.js') } })
  await win.loadURL('data:text/html,<html><body>x</body></html>')
  await new Promise(r => setTimeout(r, 500))
  const r = await win.webContents.executeJavaScript(`({ fromPreload: typeof window.__pixProbe, value: window.__pixProbe })`, true)
  w('page world sees preload window prop: ' + JSON.stringify(r))
  const r2 = await win.webContents.executeJavaScriptInIsolatedWorld(999, [{ code: `({ fromPreload: typeof window.__pixProbe, value: window.__pixProbe })` }])
  w('isolated world sees it: ' + JSON.stringify(Array.isArray(r2) ? r2[0] : r2))
  app.exit(0)
})
setTimeout(() => app.exit(2), 15000)
