const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const LOG = '/tmp/proto16.log'
const w = s => fs.appendFileSync(LOG, s + '\n')
require('../../src/translate/pix-protocol').registerPrivilegedScheme(require('electron'))
const proto = require('../../src/translate/pix-protocol')
const DIR = path.join(require('node:os').tmpdir(), 'pix-imgtrans-probe-scripts')
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false })
  await win.loadURL('data:text/html,<html><body>x</body></html>')
  const ses = win.webContents.session
  w('attach: ' + proto.attachHandler(require('electron'), ses, DIR))
  const r = await win.webContents.executeJavaScript(`fetch('pix://pix/patch.js').then(r=>'status '+r.status+' len ').catch(e=>'ERR '+e.message)`, true)
  w('fetch: ' + JSON.stringify(r))
  const r2 = await win.webContents.executeJavaScript(`fetch('pix://pix/patch.js').then(r=>r.text()).then(t=>'LEN '+t.length).catch(e=>'ERR '+e.message)`, true)
  w('fetch2: ' + JSON.stringify(r2))
  const r3 = await win.webContents.executeJavaScript(`fetch('pix://other/patch.js').then(r=>'status '+r.status).catch(e=>'ERR '+e.message)`, true)
  w('badhost: ' + JSON.stringify(r3))
  const r4 = await win.webContents.executeJavaScript(`fetch('pix://pix/main.js').then(r=>'ok').catch(e=>'ERR '+e.message)`, true)
  w('main.js: ' + JSON.stringify(r4))
  app.exit(0)
})
setTimeout(() => app.exit(2), 15000)
